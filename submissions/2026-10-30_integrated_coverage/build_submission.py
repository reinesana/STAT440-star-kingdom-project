def output_directory():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', required=True, type=Path)
    out = parser.parse_args().output_dir.resolve()
    if out.exists():
        raise SystemExit('Use a new output directory; frozen artifacts are never overwritten.')
    meta = json.loads((HERE / 'official_results.json').read_text())
    for relative, expected in meta['input_sha256_lf'].items():
        actual = hashlib.sha256((ROOT / relative).read_bytes().replace(b'\r\n', b'\n')).hexdigest()
        if actual != expected:
            raise SystemExit('Frozen dependency changed: ' + relative)
    out.mkdir(parents=True)
    return out, meta

def finish(path, meta):
    actual = digest(path)
    if actual != meta['submission_sha256']:
        raise AssertionError('Regenerated bytes differ from the submitted CSV: ' + actual)
    print(json.dumps({'submission': str(path), 'sha256': actual}))

def covered(pr,units):
    mask=np.zeros(len(pr.p),bool)
    for u in units:mask[u[2]]=True
    return mask

def at_center(pr,tree,c,required):
    c=np.round(c,9);pts=np.vstack((pr.a[required],pr.b[required]))
    r=float(f'{np.linalg.norm(pts-c,axis=1).max()+1e-6:.9f}')
    ids=np.asarray(tree.query_ball_point(c,r+1e-9),int)
    ids=ids[(np.linalg.norm(pr.a[ids]-c,axis=1)<=r)&(np.linalg.norm(pr.b[ids]-c,axis=1)<=r)]
    if not np.isin(required,ids).all():return None
    fixed=100+sum(RATES[s] for s in set(pr.surface[ids]))*(np.pi*r*r)**.85
    return (c,r,ids,fixed)

def pretreat(pr,prefix,tail,tree):
    """Small active-pipe work before large historical-only coverage work.

    Each replacement group has the exact original live assignment. Its sum of
    fixed charges must be lower than the old circle's single fixed charge.
    Conditional on a common live state at the group entry this bounds its
    construction cost for every survival subset, rather than an expected leak
    rate. Budget/timing and total score remain simulation-validated separately.
    """
    state=pr.start|covered(pr,prefix);out=list(prefix);audit=[]
    for j,old in enumerate(tail):
        rep=old[2][~state[old[2]]]
        if not len(rep):out.append(old);continue
        tmp=state.copy();group=[]
        while True:
            pending=rep[~tmp[rep]]
            if not len(pending):break
            proposals=[old]
            for i in pending:
                minimum=pr.unit([i]);centers=[minimum[0],old[0]]
                for factor in [.05,.15,.4]:
                    for angle in np.arange(8)*2*np.pi/8:
                        centers.append(minimum[0]+minimum[1]*factor*np.array([np.cos(angle),np.sin(angle)]))
                for c in centers:
                    u=at_center(pr,tree,c,np.array([i]))
                    if u is None:continue
                    active=u[2][~state[u[2]]]
                    if not np.isin(active,rep).all():continue
                    proposals.append(u)
            def rank(u):
                alive=u[2][~tmp[u[2]]]
                return (pr.cost(u,tmp)/max(len(alive),1),u[1]) if len(alive) else (float('inf'),u[1])
            u=min(proposals,key=rank);group.append(u);tmp[u[2]]=True
        union=np.unique(np.concatenate([u[2] for u in group]));assigned=union[~state[union]]
        assert np.array_equal(np.sort(assigned),np.sort(rep))
        fixed=sum(u[3] for u in group)
        if fixed<old[3]-1:
            cost=0;current=state.copy()
            for u in group:cost+=pr.cost(u,current);current[u[2]]=True
            assert np.all(current[old[2]])
            audit.append(dict(original_tail_row=j+1,active_ids=pr.p['Pipe ID'].iloc[rep].to_list(),small_circles=len(group),old_fixed=old[3],sum_small_fixed=fixed,fixed_saving_lower_bound=old[3]-fixed,
                              old_no_leak_cost=pr.cost(old,state)/100,new_no_leak_cost=cost/100))
            out.extend(group);out.append(old);state=current
        else:out.append(old);state[old[2]]=True
    return out,audit

def main():
    out, meta = output_directory()
    pr = Problem()
    source = ROOT / 'submissions/2026-10-30_center_and_split/submission_center_and_split.csv'
    parent = read(pr, source)
    assert len(parent) == 30071
    units, moves = pretreat(pr, parent[:19367], parent[19367:], cKDTree(pr.mid))
    path = out / 'submission_integrated_coverage.csv'
    candidate = write_read(pr, units, path)
    assert np.array_equal(covered(pr, candidate) & ~pr.start, covered(pr, parent) & ~pr.start)
    validate(path, pr.p, pr.hist, pr.a, pr.b, pr.mid, pr.length, pr.iron)
    (out / 'moves.json').write_text(json.dumps(moves, indent=2))
    finish(path, meta)

if __name__ == '__main__':
    main()
