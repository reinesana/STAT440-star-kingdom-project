"""Reproduce the frozen submitted geometry in a new output directory."""
from pathlib import Path
import argparse, csv, hashlib, json, math, sys
import numpy as np
import pandas as pd
from scipy.spatial import cKDTree
ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(ROOT / 'src'), str(ROOT / 'submissions/2026-10-28_ryota_early3')]
from optimize import Problem, RATES
from early_three_years import read, write_read
from build_cost_submissions import validate, digest, read_units, containment
from build_baseline import IRON
import simulate_score as sim

def output_directory():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', required=True, type=Path)
    out = parser.parse_args().output_dir.resolve()
    if out.exists():
        raise SystemExit('Use a new output directory; frozen artifacts are never overwritten.')
    meta = json.loads((HERE / 'official_results.json').read_text())
    for relative, expected in meta['input_sha256_lf'].items():
        actual = hashlib.sha256((ROOT / relative).read_bytes().replace(b'\r\n', b'\n')).hexdigest()
        if actual != expected:
            raise SystemExit('Frozen dependency changed: ' + relative)
    out.mkdir(parents=True)
    return out, meta

def finish(path, meta):
    actual = digest(path)
    if actual != meta['submission_sha256']:
        raise AssertionError('Regenerated bytes differ from the submitted CSV: ' + actual)
    print(json.dumps({'submission': str(path), 'sha256': actual}))

import search_orders as orders

def main():
    out, meta = output_directory()
    frozen = ROOT / 'submissions/2026-10-26_best20a_catboost_logrf'
    pipes, a, b = sim.load()
    lengths = pipes.len.to_numpy()
    audit = pd.read_csv(frozen / 'severity_join.audit.csv', dtype={'pipe_id': str}).set_index('pipe_id').loc[pipes['Pipe ID']]
    weights = json.loads((frozen / 'weights_2027.json').read_text())['weights']
    base = pd.read_csv(frozen / 'base_predictions_2027.csv', dtype={'pipe_id': str}).set_index('pipe_id')
    forecast = pd.read_csv(frozen / 'predictions_2027.csv', dtype={'pipe_id': str}).set_index('pipe_id')
    recomputed = sum(w * base.loc[forecast.index, k] for k, w in weights.items() if w)
    np.testing.assert_allclose(recomputed, forecast.predicted_repair_cost, rtol=1e-12, atol=1e-8)
    active = ~(pipes.mat.eq('polyurethane') | pipes.leak_date.notna()).to_numpy()
    severity = pipes['Pipe ID'].map(forecast.predicted_repair_cost).to_numpy(float)
    missing = active & ~np.isfinite(severity)
    severity[missing] = audit.old_severity.to_numpy()[missing]
    severity[~active] = 0
    np.testing.assert_allclose(severity, audit.new_severity, rtol=1e-12, atol=1e-8)
    probability = audit.leak_probability.to_numpy()
    value = np.clip(probability * (severity - 200 * lengths), 0, None)
    source = frozen / '20a_original_control.csv'
    lines = source.read_text().splitlines()
    xy, radius = sim.read_units(source)
    inside = sim.containment(xy, radius, a, b, lengths)
    order = orders.order_dynamic(inside, radius, pipes, lengths,
                                 np.zeros((len(pipes), len(sim.YEARS))),
                                 static_value=value, blend=1.)
    # Preserve the bytes of the evaluated Windows-checkout CSV (CRLF).
    path = out / '21a_corrected_order.csv'
    path.write_bytes(('\r\n'.join(lines[k] for k in order) + '\r\n').encode('utf-8'))
    history = pd.read_csv(ROOT / 'data/train.csv', dtype={'Pipe ID': str})
    validate(path, pipes, history, a, b, (a+b)/2, lengths, pipes.Material.isin(IRON).to_numpy())
    finish(path, meta)

if __name__ == '__main__':
    main()
