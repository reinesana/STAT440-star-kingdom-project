"""Reproduce the frozen submitted geometry in a new output directory."""
from pathlib import Path
import argparse, csv, hashlib, json, math, sys
import numpy as np
import pandas as pd
from scipy.spatial import cKDTree
ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(ROOT / 'src'), str(ROOT / 'submissions/2026-10-28_ryota_early3')]
from optimize import Problem, RATES
from early_three_years import read, write_read
from build_cost_submissions import validate, digest, read_units, containment
from build_baseline import IRON
import simulate_score as sim

def output_directory():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', required=True, type=Path)
    out = parser.parse_args().output_dir.resolve()
    if out.exists():
        raise SystemExit('Use a new output directory; frozen artifacts are never overwritten.')
    meta = json.loads((HERE / 'official_results.json').read_text())
    for relative, expected in meta['input_sha256_lf'].items():
        actual = hashlib.sha256((ROOT / relative).read_bytes().replace(b'\r\n', b'\n')).hexdigest()
        if actual != expected:
            raise SystemExit('Frozen dependency changed: ' + relative)
    out.mkdir(parents=True)
    return out, meta

def finish(path, meta):
    actual = digest(path)
    if actual != meta['submission_sha256']:
        raise AssertionError('Regenerated bytes differ from the submitted CSV: ' + actual)
    print(json.dumps({'submission': str(path), 'sha256': actual}))

def repair_baseline(OUT):
    REPO = ROOT
    source = ROOT / "submissions/2026-10-28_ryota_shrink_after_work/outputs/submission_shrink_after_work.csv"
    p,a,b=sim.load(); h=pd.read_csv(REPO/'data/train.csv'); mid=(a+b)/2; lengths=p.len.to_numpy()
    units=read_units(source); tree=cKDTree(mid); inside=containment(units,tree,a,b)
    covered=np.zeros(len(p),bool)
    for ids in inside: covered[ids]=True
    iron=p.Material.isin(IRON).to_numpy(); start=(p.Material.eq('polyurethane')|p.leak_date.notna()).to_numpy()
    missing=np.flatnonzero(iron & ~covered)
    assert start[missing].all()
    extra=[(np.round(mid[i],9),float(f'{lengths[i]/2+1e-6:.9f}')) for i in missing]
    extra_inside=containment(extra,tree,a,b)
    # At the end of the existing plan these pipes are guaranteed polyurethane,
    # regardless of the leak realization, if the original plan completes.
    safe=start|covered
    unsafe=[j for j,ids in enumerate(extra_inside) if not safe[ids].all()]
    for j in unsafe:
        i=missing[j]; direction=b[i]-a[i]; normal=np.array([-direction[1],direction[0]])/lengths[i]
        found=[]
        for shift in np.concatenate(([0.],np.geomspace(.001,10000,100),-np.geomspace(.001,10000,100))):
            c=np.round(mid[i]+shift*normal,9)
            r=float(f'{max(np.linalg.norm(a[i]-c),np.linalg.norm(b[i]-c))+1e-6:.9f}')
            ids=containment([(c,r)],tree,a,b)[0]
            if i in ids and safe[ids].all(): found.append((r,c,ids))
            if found and abs(shift)>found[0][0]*2: break
        if found:
            r,c,ids=min(found,key=lambda x:x[0]); extra[j]=(c,r);extra_inside[j]=ids
    unresolved=[j for j,ids in enumerate(extra_inside) if not safe[ids].all()]
    for j in unresolved:
        i=missing[j]
        def penalty(c,r,ids):
            rep=ids[~safe[ids]]
            return 0. if not len(rep) else 100+sum(RATES[s] for s in set(p.Surface.iloc[ids]))*(np.pi*r*r)**.85+200*lengths[rep].sum()
        c,r=extra[j]; best=(penalty(c,r,extra_inside[j]),c,r,extra_inside[j])
        for factor in [.01,.03,.1,.25,.5,1.,2.,4.,8.]:
            for theta in np.arange(32)*2*np.pi/32:
                c=np.round(mid[i]+factor*lengths[i]*np.array([np.cos(theta),np.sin(theta)]),9)
                r=float(f'{max(np.linalg.norm(a[i]-c),np.linalg.norm(b[i]-c))+1e-6:.9f}')
                ids=containment([(c,r)],tree,a,b)[0]
                cost=penalty(c,r,ids)
                if i in ids and cost<best[0]:best=(cost,c,r,ids)
        _,c,r,ids=best;extra[j]=(c,r);extra_inside[j]=ids
    unresolved=[j for j,ids in enumerate(extra_inside) if not safe[ids].all()]
    pd.DataFrame([{'pipe_id':p['Pipe ID'].iloc[missing[j]],'incidental_ids':','.join(p['Pipe ID'].iloc[extra_inside[j][~safe[extra_inside[j]]]])} for j in unresolved]).to_csv(OUT/'unresolved_repair.csv',index=False)
    print('Supplementary circles requiring incidental replacements:',len(unresolved),flush=True)
    path=OUT/'baseline_full_original_iron.csv'
    # Preserve the exact original byte prefix and all original geometry/order.
    assert source.read_bytes().endswith(b'\n')
    path.write_bytes(source.read_bytes())
    with path.open('a',newline='',encoding='utf-8') as f:
        w=csv.writer(f)
        for c,r in extra: w.writerow([f'({c[0]:.9f}, {c[1]:.9f})',f'{r:.9f}'])
    report=validate(path,p,h,a,b,mid,lengths,iron)
    assert report['completion_year']<=2051
    return path

def unit_at(pr,tree,c,required):
    c=np.round(c,9); points=np.vstack((pr.a[required],pr.b[required]))
    r=float(f'{np.max(np.linalg.norm(points-c,axis=1))+1e-6:.9f}')
    ids=np.asarray(tree.query_ball_point(c,r+1e-9),int)
    ids=ids[(np.linalg.norm(pr.a[ids]-c,axis=1)<=r)&(np.linalg.norm(pr.b[ids]-c,axis=1)<=r)]
    if not np.isin(required,ids).all():return None
    fixed=100+sum(RATES[s] for s in set(pr.surface[ids]))*(math.pi*r*r)**.85
    return (c,r,ids,fixed)

def search(pr,base,tree,move=True):
    state=pr.start.copy();covered=np.zeros(len(pr.p),bool);out=[];audit=[]
    for j,old in enumerate(base):
        ids=old[2];rep=ids[~state[ids]];required=ids[~covered[ids]];chosen=[old]
        oldcost=pr.cost(old,state)
        if len(rep) and len(required):
            proposals=[]
            # Fixed-center radius-only arm isolates the radius contribution.
            u=unit_at(pr,tree,old[0],required)
            if u is not None:proposals.append([u])
            if move:
                pts=np.vstack((pr.a[required],pr.b[required]));center=pts.mean(axis=0)
                centers=[center,(pts.min(axis=0)+pts.max(axis=0))/2]
                minimum=pr.unit(required) if len(required)<=6 else None
                if minimum is not None:centers.append(minimum[0])
                # Prune centers when even the minimum enclosing disk with only
                # mandatory surfaces cannot save a dollar. This bound is valid
                # regardless of incidental pipes at any proposed center.
                lower=(100+sum(RATES[s] for s in set(pr.surface[required]))*(np.pi*minimum[1]**2)**.85) if minimum is not None else 0
                if old[3]-lower>1:
                    for factor in [.01,.05,.15,.4]:
                        for theta in np.arange(12)*2*np.pi/12:
                            centers.append(old[0]+old[1]*factor*np.array([np.cos(theta),np.sin(theta)]))
                for c in centers:
                    u=unit_at(pr,tree,c,required)
                    if u is not None:proposals.append([u])
                if 1<len(required)<=12:
                    for axis in [0,1]:
                        order=required[np.argsort(pr.mid[required,axis],kind='stable')]
                        cut=len(order)//2
                        proposals.append([pr.unit(order[:cut]),pr.unit(order[cut:])])
            best=oldcost
            for group in proposals:
                union=np.unique(np.concatenate([u[2] for u in group]))
                # Preserve exact currently live assignment and all new prefix coverage.
                if not np.array_equal(np.sort(union[~state[union]]),np.sort(rep)):continue
                if not np.isin(required,union).all():continue
                tmp=state.copy();cost=0
                for u in group:cost+=pr.cost(u,tmp);tmp[u[2]]=True
                if cost<best-100:best=cost;chosen=group
            if best<oldcost:
                audit.append({'original_row':j+1,'old_radius':old[1],'new_radii':[u[1] for u in chosen],
                              'old_cost':oldcost/100,'new_cost':best/100,'split':len(chosen)>1})
        for u in chosen:covered[u[2]]=True;state[u[2]]=True;out.append(u)
        assert covered[ids].all()
        if j%4000==0: print('search',move,j,'accepted',len(audit),flush=True)
    return out,audit

def main():
    out, meta = output_directory()
    pr = Problem()
    baseline = read(pr, repair_baseline(out))
    units, moves = search(pr, baseline, cKDTree(pr.mid))
    path = out / 'submission_center_and_split.csv'
    write_read(pr, units, path)
    validate(path, pr.p, pr.hist, pr.a, pr.b, pr.mid, pr.length, pr.iron)
    (out / 'moves.json').write_text(json.dumps(moves, indent=2))
    finish(path, meta)

if __name__ == '__main__':
    main()
